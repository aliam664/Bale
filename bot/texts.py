"""متن‌های فارسی ربات. (بله همهٔ متن‌ها را Markdown در نظر می‌گیرد؛ از * و _ با فاصله استفاده کنید.)"""
from __future__ import annotations

import re

_MD_CHARS = re.compile(r"[*_`\[\]()]")


def safe(text: str) -> str:
    """حذف کاراکترهای Markdown از متن‌های کاربر (مثل نام) تا پیام به‌هم نریزد."""
    return _MD_CHARS.sub("", text or "").strip() or "بازیکن"


